import test from 'node:test';
import assert from 'node:assert/strict';
import pg from 'pg';
import {randomUUID} from 'node:crypto';
import {migrate} from '../server/migrate.mjs';
import {createApp} from '../server/app.mjs';
import {createProjectService} from '../server/project-service.mjs';
const url=process.env.TEST_DATABASE_URL;
test('PostgreSQL migration, API, approval/report isolation, conflicts and append-only audit',{skip:!url},async()=>{
  const schema='test_'+randomUUID().replaceAll('-','');const admin=new pg.Pool({connectionString:url});
  await admin.query(`CREATE SCHEMA ${schema}`);
  const pool=new pg.Pool({connectionString:url,options:`-c search_path=${schema}`});
  let server;
  try{
    await migrate(pool);await migrate(pool);
    assert.equal((await pool.query('SELECT count(*)::int AS n FROM schema_migrations')).rows[0].n,1);
    const owner={id:'owner',name:'과제 대표',role:'project-representative',team:'AT팀'};
    const reviewer={id:'lead',name:'AT 팀장',role:'team-lead',team:'AT팀'};
    const stranger={id:'other',name:'일반 구성원',role:'participant',team:'AT팀'};
    const service=createProjectService(pool);
    const input={title:"SQL ' 문자 포함 과제",team:'AT팀',tech:['All Tech'],planMode:'cumulative-percent-v1',stepPlanMode:'weighted-steps-v1',unit:'%',startDate:'2025-01-01',endDate:'2025-02-28',steps:[{id:'s1',name:'분석',weight:40,startDate:'2025-01-01',endDate:'2025-02-28',monthly:{'2025-01':{goal:50},'2025-02':{goal:100}}},{id:'s2',name:'검증',weight:60,startDate:'2025-01-01',endDate:'2025-02-28',monthly:{'2025-01':{goal:50},'2025-02':{goal:100}}}],monthly:{},_audit:[{fake:true}],_ownerId:'attacker',status:'완료'};
    let project=await service.create(input,owner);
    assert.equal(project._ownerId,'owner');assert.equal(project.status,'계획');assert.equal(project._audit,undefined);assert.equal(project.monthly['2025-01'].goal,50);
    assert.equal((await service.list(owner)).length,1);
    await assert.rejects(service.reports(project.id,project._revision,{stepReports:{}},stranger),e=>e.status===403);
    const candidate=structuredClone(project);candidate.steps[0].monthly['2025-01'].goal=60;
    project=await service.request(project.id,project._revision,candidate,'목표 조정',owner);
    const requestId=project._changeRequests[0].id;
    assert.equal(project.steps[0].monthly['2025-01'].goal,50);
    project=await service.reports(project.id,project._revision,{stepReports:{s1:{'2025-01':{actual:80}},s2:{'2025-01':{actual:80}}}},owner);
    assert.equal(project.monthly['2025-01'].actual,80);
    const revision=project._revision;
    const writes=await Promise.allSettled([service.reports(project.id,revision,{stepReports:{s1:{'2025-02':{actual:100}}}},owner),service.reports(project.id,revision,{stepReports:{s1:{'2025-02':{actual:100}}}},owner)]);
    assert.equal(writes.filter(r=>r.status==='fulfilled').length,1);
    assert.equal(writes.find(r=>r.status==='rejected').reason.status,409);
    project=await service.get(project.id,owner);
    await assert.rejects(service.decide(project.id,project._revision,requestId,'approved','자기 승인',owner));
    project=await service.decide(project.id,project._revision,requestId,'approved','확인 완료',reviewer);
    assert.equal(project.steps[0].monthly['2025-01'].goal,60);
    assert.equal(project.stepReports.s1['2025-01'].actual,80);
    assert.equal(project.monthly['2025-01'].actual,80);
    const history=await service.history(project.id,owner);assert.equal(history.length,5);
    assert.ok(history.every(e=>e.actor.id));
    await assert.rejects(pool.query('DELETE FROM audit_events WHERE project_id=$1',[project.id]),/append-only/);
    assert.equal((await pool.query('SELECT count(*)::int AS n FROM audit_events')).rows[0].n,5);
    const before=project._revision;
    await assert.rejects(service.reports(project.id,before,{stepReports:{unknown:{'2025-01':{actual:100}}}},owner),e=>e.status===422);
    assert.equal((await service.get(project.id,owner))._revision,before);
    const app=createApp({pool,authenticate:async req=>req.headers['x-test-auth']==='yes'?owner:null});
    server=await new Promise(resolve=>{const s=app.listen(0,'127.0.0.1',()=>resolve(s));});
    const base=`http://127.0.0.1:${server.address().port}`;
    assert.equal((await fetch(base+'/api/health')).status,200);
    assert.equal((await fetch(base+'/api/projects')).status,401);
    const get=await fetch(base+`/api/projects/${project.id}`,{headers:{'x-test-auth':'yes'}});
    assert.equal(get.status,200);assert.equal(get.headers.get('etag'),`"${before}"`);
    const conflict=await fetch(base+`/api/projects/${project.id}/reports`,{method:'PUT',headers:{'x-test-auth':'yes','Content-Type':'application/json'},body:JSON.stringify({stepReports:{}})});
    assert.equal(conflict.status,409);
    const invalid=await fetch(base+'/api/projects',{method:'POST',headers:{'x-test-auth':'yes','Content-Type':'application/json'},body:'{'});
    assert.equal(invalid.status,400);
  }finally{if(server)await new Promise(resolve=>server.close(resolve));await pool.end();await admin.query(`DROP SCHEMA ${schema} CASCADE`);await admin.end();}
});
